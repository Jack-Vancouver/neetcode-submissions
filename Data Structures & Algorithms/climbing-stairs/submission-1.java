class Solution {
    public int climbStairs(int n) {
        // Base Cases: 1 阶和 2 阶极其直观，直接返回
        if (n == 1) {
            return 1;
        }
        if (n == 2) {
            return 2;
        }

        // prev2 代表往下走两步的台阶 (即 n-2 阶) 的走法数
        int prev2 = 1; 
        
        // prev1 代表往下走一步的台阶 (即 n-1 阶) 的走法数
        int prev1 = 2; 
        
        int current = 0; // 当前所在台阶的走法数

        // 从第 3 阶开始往上爬，一直爬到第 n 阶
        for (int i = 3; i <= n; i++) {
            // 核心状态转移方程：当前走法 = 前一阶走法 + 前两阶走法
            current = prev1 + prev2;
            
            // 【灵魂操作：毛毛虫向前滚动】
            // 我们准备计算下一阶了，所以历史数据要集体往前挪一步
            prev2 = prev1;   // 老的 prev1 变成了新的 prev2
            prev1 = current; // 刚算出来的 current 变成了新的 prev1
        }

        return current;
    }
}

//在面对 DP 问题时，我们要用“时光倒流”的方法去思考——死死盯住最后一步！

//假设现在有 100 阶楼梯。请问，你在跨出最后一步之前，人站在哪里？
//因为你每次只能走 1 步或 2 步，所以你必然且只能站在两个地方：
//你站在第 99 阶（然后跨 1 步上来）。
//你站在第 98 阶（然后跨 2 步上来）。
//除此之外，绝对没有第三种可能！

//这就引出了 DP 最伟大的状态转移方程：
//走到第 100 阶的方法总数 = 走到第 99 阶的方法数 + 走到第 98 阶的方法数
//抽象成数学公式就是：F(n) = F(n-1) + F(n-2)

//Aha! 时刻：
//等你写出这个公式，你会震惊地发现，这不就是大名鼎鼎的斐波那契数列 (Fibonacci) 吗！