class Solution {
    public int numDecodings(String s) {
        // 0. 极端情况与地雷防御：如果密文为空，或者开头就是 '0'，直接死刑
        if (s == null || s.length() == 0 || s.charAt(0) == '0') {
            return 0;
        }

        // prev2 代表走两步之前的翻译方法数 (相当于 dp[i-2])
        // 为什么设为 1？因为如果遇到合法的两位数（比如开头是 "22"），
        // 那么把 "22" 整体当作一步切下来的走法是 1 种。这是基础底座。
        int prev2 = 1; 
        
        // prev1 代表走一步之前的翻译方法数 (相当于 dp[i-1])
        // 因为 s.charAt(0) != '0' 已经验证过了，所以第一个字符的合法切法是 1 种。
        int prev1 = 1; 

        // current 代表当前处理到第 i 个字符时的总翻译方法数
        int current = 0;

        // 从密文的第 2 个字符（索引 1）开始挨个破译
        for (int i = 1; i < s.length(); i++) {
            current = 0; // 每一轮开始前先清零

            // 选择 A：只切当前 1 个字符
            // 只要当前字符不是 '0'，这条路就通，继承 prev1
            if (s.charAt(i) != '0') {
                current += prev1;
            }

            // 选择 B：把当前字符和前一个字符打包切 2 个
            // 提取出这两个字符组成的两位数
            int twoDigit = (s.charAt(i - 1) - '0') * 10 + (s.charAt(i) - '0');
            // 只要这个两位数在 10 到 26 之间，这条路就通，继承 prev2
            if (twoDigit >= 10 && twoDigit <= 26) {
                current += prev2;
            }

            // 【灵魂操作：毛毛虫向前滚动】
            prev2 = prev1;
            prev1 = current;
        }

        return prev1; // 走到最后，prev1 就是最终的总方法数
    }
}

// 回忆一下爬楼梯的公式：走到当前台阶的走法 = 跨 1 步上来 + 跨 2 步上来。
// 翻译密码本质上就是爬楼梯：你每次可以从密文里切 1 个数字（跨 1 步），或者切 2 个数字（跨 2 步）。
// 唯一的区别是，现在你跨步前必须先“看一眼台阶是不是塌了”：
// 	1.	切 1 个数字（跨 1 步）：只要当前这个数字不是 '0'，你就能单独切下它。此时的方法数继承自上一步（‭$dp$‬‭$[$‬‭$i$‬‭$\hphantom{}-1$‬‭$]$‬）。
// 	2.	切 2 个数字（跨 2 步）：只要当前数字和前一个数字组成的两位数在 10 到 26 之间，你就能把这俩打包切下。此时的方法数继承自上两步（‭$dp$‬‭$[$‬‭$i$‬‭$\hphantom{}-2$‬‭$]$‬）。
// 总方法数就是这两种情况能走通的数量之和！


// 详细拆解：如何优雅地避开 O(N) 空间？
// 很多新手在做这道题时，为了方便处理边界，会选择开辟一个 int[] dp = new int[s.length() + 1]。
// 这是因为第 1 个字符需要依赖一个“虚空”的第 0 个状态。
// 我们的滚动变量写法极大地优化了这一点：
// 我们直接把 prev2 = 1 作为那个“虚空”的基础状态。
// 当处理到第二个字符时（比如密文是 "22"，当前在索引 1）：
// •	跨 1 步：第二个 '2' 合法，current += prev1 (即 1)。
// •	跨 2 步："22" 合法，current += prev2 (即 1)。
// •	所以走到索引 1 时的总方法 current = 2。
// 这种巧妙的初始值设定，避免了繁琐的数组越界判断，是这套代码最具含金量的地方。


// 复杂度评估
// •	时间复杂度：O(N)。
// 我们只需要写一个 for 循环把字符串从头扫到尾，
// 提取两位数的操作 (s.charAt(i - 1) - '0') * 10 + (s.charAt(i) - '0') 是极速的O(1)数学计算，
// 没有使用任何耗时的 substring 或 Integer.parseInt。
// •	空间复杂度：O(1)。
// 我们依然只用了 prev1、prev2 和 current 三个整型变量，完全做到了内存的最小化。